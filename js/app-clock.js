/**
 * Время приложения с пользовательским смещением (Настройки → «Смещение времени»).
 *
 * Смещение — поправка только для ПОКАЗА времени (часы на экране, «14:05» у передач): когда у
 * телевизора не тот часовой пояс, сам момент «сейчас» у него верный (TV берёт время из сети),
 * неверно только то, как он его показывает. Поэтому:
 *   - AppClock.now() — настоящее «сейчас», по нему ищется «что идёт» и считается архив;
 *   - AppClock.local(t) — тот же момент, сдвинутый для вывода (getHours/getDay/toDateString).
 * Раньше смещение сдвигало и now(), и тогда программа показывала передачу на N часов не ту.
 */
const AppClock = (() => {
    let offsetMs = 0;

    return {
        now: () => new Date(),
        /** t: Date или миллисекунды → Date для вывода часов и минут с учётом смещения */
        local: (t) => new Date((t instanceof Date ? t.getTime() : Number(t)) + offsetMs),
        /** hours: число часов, может быть отрицательным */
        setOffsetHours: (hours) => { offsetMs = (Number(hours) || 0) * 3600 * 1000; }
    };
})();

if (typeof module !== 'undefined') module.exports = { AppClock };
